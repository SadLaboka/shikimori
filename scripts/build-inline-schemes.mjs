import { readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import { SCHEMES, REVISION, BASE_IMPORTS, sha256 } from '../extensions/firefox/catalog.mjs';
import { AVATAR_HOVER_CSS } from '../extensions/firefox/avatar-hover.mjs';
import { extractLocal } from '../tools/preview/css.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = new URL('../extensions/firefox/inline-schemes.mjs', import.meta.url);
export function pinnedSource(url) {
  const match = /^https:\/\/raw\.githubusercontent\.com\/SadLaboka\/shikimori\/([a-f0-9]{40})\/(styles_optimized\.css|css\/base\/main_code_[123]\.css|css\/base\/main_code_4mob\.css|css\/themes\/[a-z-]+\/styles\.css)$/.exec(url);
  if (!match) throw new Error('Inline source must be an exact approved repository commit and CSS path.');
  return { revision: match[1], file: match[2] };
}
export async function checkedSource(url, expectedHash) {
  const { revision, file } = pinnedSource(url);
  const text = execFileSync('git', ['show', `${revision}:${file}`], { cwd: root, encoding: 'utf8', maxBuffer: 1024 * 1024 });
  if (await sha256(text) !== expectedHash) throw new Error(`Pinned CSS hash differs: ${file}`);
  return text;
}
export async function generateInlineSchemes() {
  const meta = JSON.parse(await readFile(new URL('../extensions/firefox/inline-sources.json', import.meta.url), 'utf8'));
  if (meta.version !== 1 || meta.fonts.file !== 'vendor/google-fonts.css') throw new Error('Unsupported inline source manifest.');
  const fonts = await readFile(new URL('../vendor/google-fonts.css', import.meta.url), 'utf8');
  if (await sha256(fonts) !== meta.fonts.sha256 || (fonts.match(/@font-face/g) ?? []).length !== 5 || extractLocal(fonts).imports.length) {
    throw new Error('Font snapshot differs from the reviewed five font faces.');
  }
  const baseUrls = BASE_IMPORTS.slice(2).map(line => line.match(/url\("([^"]+)"\)/)?.[1]);
  if (baseUrls.length !== 4 || JSON.stringify(meta.bases.map(item => item.url)) !== JSON.stringify(baseUrls)) throw new Error('Base import order differs.');
  const bases = await Promise.all(meta.bases.map(async item => `/* Source: ${item.url} */\n${await checkedSource(item.url, item.sha256)}`));
  const schemes = {};
  for (const scheme of SCHEMES) {
    const url = `https://raw.githubusercontent.com/SadLaboka/shikimori/${scheme.revision ?? REVISION}/${scheme.file}`;
    const source = await checkedSource(url, scheme.sourceSha256);
    const full = [fonts, ...bases, `/* Source: ${url} */\n${source.replace(/^@import[^\r\n]+;[\r\n]*/gm, '')}`, AVATAR_HOVER_CSS].join('\n\n');
    // The same comment/import extraction already models Shikimori. Removing
    // comments retains room for CRLF when its textarea saves the full payload.
    const css = extractLocal(full).user.trim();
    const crlf = css.replaceAll('\n', '\r\n');
    if (extractLocal(css).imports.length || crlf.length > 512000 || Buffer.byteLength(crlf) > 512000) throw new Error(`Inline payload exceeds the supported limit: ${scheme.id}`);
    const approved = meta.schemes[scheme.id];
    if (await sha256(css) !== approved?.sha256 || css.length !== approved.characters || crlf.length !== approved.crlfCharacters) {
      throw new Error(`Inline payload differs from the reviewed source: ${scheme.id}`);
    }
    schemes[scheme.id] = css;
  }
  if (JSON.stringify(Object.keys(meta.schemes)) !== JSON.stringify(Object.keys(schemes))) throw new Error('Inline catalog differs from SCHEMES.');
  const module = '// Generated by scripts/build-inline-schemes.mjs. Do not edit.\n' +
    '// Pinned CSS, font sources and author notices: inline-sources.json and the repository CSS/vendor archives.\n' +
    `export const INLINE_SCHEMES = Object.freeze(${JSON.stringify(schemes, null, 2)});\n`;
  return { module, schemes, meta };
}
if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const mode = process.argv[2];
  if (!['--check', '--write'].includes(mode)) throw new Error('Use --check or --write.');
  const result = await generateInlineSchemes();
  if (mode === '--write') await writeFile(output, result.module);
  else if (await readFile(output, 'utf8') !== result.module) throw new Error('Inline bundles are stale.');
  console.log(JSON.stringify({ mode, schemes: Object.fromEntries(Object.entries(result.schemes).map(([id, css]) => [id, { characters: css.length, sha256: result.meta.schemes[id].sha256 }])) }));
}
